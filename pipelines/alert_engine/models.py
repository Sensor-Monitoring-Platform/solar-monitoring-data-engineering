from __future__ import annotations

from dataclasses import dataclass, field
from datetime import datetime
from enum import Enum
from typing import Any, Optional


# ============================================================
# ENUMS
# ============================================================


class AlertSeverity(str, Enum):
    INFO = "INFO"
    WARNING = "WARNING"
    CRITICAL = "CRITICAL"
    EMERGENCY = "EMERGENCY"


class AlertStatus(str, Enum):
    OPEN = "OPEN"
    ACKNOWLEDGED = "ACKNOWLEDGED"
    RESOLVED = "RESOLVED"


class SensorState(str, Enum):
    ONLINE = "ONLINE"
    OFFLINE = "OFFLINE"
    UNKNOWN = "UNKNOWN"


class EvaluationStatus(str, Enum):
    NORMAL = "NORMAL"
    WARNING = "WARNING"
    CRITICAL = "CRITICAL"
    EMERGENCY = "EMERGENCY"
    INVALID = "INVALID"


class RuleOperator(str, Enum):
    GREATER_THAN = ">"
    GREATER_THAN_OR_EQUAL = ">="
    LESS_THAN = "<"
    LESS_THAN_OR_EQUAL = "<="
    EQUAL = "=="
    NOT_EQUAL = "!="


# ============================================================
# SENSOR EVENT
# ============================================================


@dataclass(frozen=True)
class SensorEvent:
    """
    A single sensor reading entering the Alert Engine.

    This is intentionally close to the event generated by
    simulate_sensors.py.
    """

    device_id: str
    device_type: str

    plant_id: str
    machine_id: str

    timestamp: datetime

    reading_value: Optional[float]
    reading_unit: Optional[str]

    quality_flag: Optional[str] = None
    firmware_version: Optional[str] = None

    ingestion_timestamp: Optional[datetime] = None

    # Optional fields that may appear as the generator evolves.
    error_code: Optional[str] = None
    calibration_status: Optional[str] = None
    sensor_health: Optional[str] = None

    # Preserve unexpected fields for forward compatibility.
    metadata: dict[str, Any] = field(default_factory=dict)


# ============================================================
# ALERT RULE
# ============================================================


@dataclass(frozen=True)
class AlertRule:
    """
    A single executable alert rule.

    Example:

        TEMP_PROCESS_HIGH_CRITICAL
        value > 210
        severity = CRITICAL
    """

    rule_id: str

    device_type: str

    operator: RuleOperator

    threshold: float

    severity: AlertSeverity

    alert_type: str

    message_template: str

    enabled: bool = True

    # Optional rule-level controls.
    cooldown_seconds: int = 0

    # If true, the rule represents a safety-critical condition.
    safety_critical: bool = False


# ============================================================
# RULE EVALUATION
# ============================================================


@dataclass(frozen=True)
class RuleEvaluation:
    """
    Result of evaluating one SensorEvent against one rule.
    """

    status: EvaluationStatus

    rule_id: Optional[str]

    severity: Optional[AlertSeverity]

    triggered: bool

    value: Optional[float]

    threshold: Optional[float]

    message: Optional[str] = None

    reason: Optional[str] = None


# ============================================================
# SENSOR STATE
# ============================================================


@dataclass
class SensorRuntimeState:
    """
    Runtime state maintained by the Alert Engine for each sensor.

    This is NOT the permanent sensor metadata.

    It represents what the engine currently knows about the sensor.
    """

    device_id: str

    state: SensorState = SensorState.UNKNOWN

    last_event_timestamp: Optional[datetime] = None
    last_seen_timestamp: Optional[datetime] = None

    last_value: Optional[float] = None

    consecutive_invalid_events: int = 0

    updated_at: Optional[datetime] = None


# ============================================================
# ALERT
# ============================================================


@dataclass
class Alert:
    """
    Persistent representation of an active/resolved alert.
    """

    alert_id: str

    fingerprint: str

    device_id: str
    device_type: str

    plant_id: str
    machine_id: str

    rule_id: str
    alert_type: str

    severity: AlertSeverity
    status: AlertStatus

    trigger_value: Optional[float]
    threshold_value: Optional[float]

    unit: Optional[str]

    event_timestamp: datetime
    detected_timestamp: datetime

    first_seen_timestamp: datetime
    last_seen_timestamp: datetime

    occurrence_count: int = 1

    message: str = ""

    acknowledged_timestamp: Optional[datetime] = None
    resolved_timestamp: Optional[datetime] = None

    created_at: Optional[datetime] = None
    updated_at: Optional[datetime] = None


# ============================================================
# ALERT EVENT
# ============================================================


class AlertEventType(str, Enum):
    CREATED = "ALERT_CREATED"
    UPDATED = "ALERT_UPDATED"
    ACKNOWLEDGED = "ALERT_ACKNOWLEDGED"
    RESOLVED = "ALERT_RESOLVED"
    SENSOR_OFFLINE = "SENSOR_OFFLINE"
    SENSOR_RECOVERED = "SENSOR_RECOVERED"


@dataclass(frozen=True)
class AlertEvent:
    """
    Event emitted by the Alert Engine.

    This is what can eventually be sent through WebSocket,
    Kafka, Redis Streams, etc.
    """

    event_type: AlertEventType

    alert_id: Optional[str]

    device_id: str

    plant_id: str
    machine_id: str

    severity: Optional[AlertSeverity]

    timestamp: datetime

    message: str

    alert: Optional[Alert] = None

    detection_latency_ms: Optional[float] = None
    notification_latency_ms: Optional[float] = None

    metadata: dict[str, Any] = field(default_factory=dict)